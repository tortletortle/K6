def rewrite_detail(name: str, detail: str) -> None:
    path = topics / name
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    marker = '<a id="detail-'
    pos = text.find(marker)
    if pos != -1:
        import re
        text = text[:pos].rstrip()
        lines = text.splitlines()
        while lines:
            tail = lines[-1].strip()
            if not tail:
                lines.pop()
                continue
            if re.match(r"^##\s*\?+$", tail) or re.match(r"^##\s*本章详细讲解\s*$", tail):
                lines.pop()
                continue
            break
        text = "\n".join(lines).rstrip() + "\n"
    text = text.rstrip() + "\n\n" + detail.strip() + "\n"
    path.write_text(text, encoding="utf-8")


