def rewrite_double(name: str, detail: str) -> None:
    path = topics / name
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    marker = '<a id="double-'
    pos = text.find(marker)
    if pos != -1:
        text = text[:pos].rstrip()
        lines = text.splitlines()
        while lines:
            tail = lines[-1].strip()
            if not tail:
                lines.pop()
                continue
            if re.match(r"^##\\s*本章加倍细化\\s*$", tail) or re.match(r"^##\\s*\\?+$", tail):
                lines.pop()
                continue
            break
        text = "\\n".join(lines).rstrip() + "\\n"
    text = text.rstrip() + "\\n\\n" + detail.strip() + "\\n"
    path.write_text(text, encoding="utf-8")


def main() -> None:
    for name, detail in DOUBLE_DETAILS.items():
        rewrite_double(name, detail)


if __name__ == "__main__":
    main()
    print("Double-detail batch3 done.")
